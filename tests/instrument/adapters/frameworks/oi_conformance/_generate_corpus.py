"""Generator for the OpenInference cross-language conformance corpus.

Emits ``spans.otlp.json`` — a proto3-JSON ``ExportTraceServiceRequest`` carrying
one span per mapping lane. It is the SHARED INPUT fed to BOTH the Python importer
(``layerlens.instrument.adapters.frameworks.openinference.span_to_events``) and the
Go OTLP bridge (``atlas-app/apps/otlp-ingest/ingest/openinference.go``), so the two
implementations of the SAME span->event contract can be pinned against each other.

WHAT THIS CORPUS IS — read before trusting it
---------------------------------------------
These spans are SYNTHETIC, DELIBERATELY-CONSTRUCTED CONTRACT INPUTS. They are NOT
a recording of a production run and must never be presented as one. Every lane
exists to exercise one branch of the mapping (a span kind, a fallback, a cap, an
honest omission), including branches a real trace shows only rarely (GUARDRAIL,
EVALUATOR, RERANKER) or that only appear under failure.

They are honest for their purpose — pinning a pure function's dispatch, field
names, and caps — because the ORACLE they are compared against is generated from
the REAL Go bridge, never hand-written. What is asserted is agreement between two
real implementations over a stated input; nothing here is presented as measured
production data.

The attribute KEYS and the LLM lane's values are taken from the real OpenInference
semantic conventions as already exercised by the real wire fixture at
``atlas-app/apps/otlp-ingest/ingest/testdata/otlp-fixtures/03-openinference-arize.otlp.json``
(itself generated by ateam's ``_generator/generate.py``).

Determinism: ids are fixed literals, timestamps are fixed epoch-ns literals, and
the file is written with ``sort_keys=True, indent=2`` + trailing newline. Running
this generator twice produces a byte-identical file.

Run:
    python tests/instrument/adapters/frameworks/oi_conformance/_generate_corpus.py
"""

