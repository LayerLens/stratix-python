def build() -> Dict[str, Any]:
    spans: List[Dict[str, Any]] = []
    for span_id, name, code, message, attrs in LANES:
        span: Dict[str, Any] = {
            "attributes": [{"key": k, "value": v} for k, v in sorted(attrs.items())],
            "endTimeUnixNano": str(END_NS),
            "kind": 3,
            "name": name,
            "parentSpanId": "",
            "spanId": span_id,
            "startTimeUnixNano": str(START_NS),
            "status": {"code": code, "message": message},
            "traceId": TRACE_ID,
        }
        spans.append(span)
    return {
        "resourceSpans": [
            {
                "resource": {
                    "attributes": [
                        {"key": "service.name", "value": s("oi-conformance")},
                    ]
                },
                "scopeSpans": [
                    {
                        "scope": {
                            "name": "openinference.instrumentation.openai",
                            "version": "0.1.18",
                        },
                        "spans": spans,
                    }
                ],
            }
        ]
    }


def main() -> None:
    out = pathlib.Path(__file__).parent / "spans.otlp.json"
    out.write_text(json.dumps(build(), indent=2, sort_keys=True) + "\n")
    print(f"wrote {out} ({len(LANES)} spans)")


if __name__ == "__main__":
    main()
